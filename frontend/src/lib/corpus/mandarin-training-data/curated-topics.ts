// These curated prompts are rewritten into short spoken Mandarin rather than
// copied lists. They were shaped from official/authoritative usage patterns
// such as 12306 priority-passenger guidance, 120 emergency call guidance,
// public-service language norms, and common high-frequency device workflows.
const MIN_TEXT_LENGTH = 6
const MAX_TEXT_LENGTH = 16

function countVisibleChars(text: string): number {
  return Array.from(text.replace(/\s+/g, '')).length
}

function buildExercises(
  category: MandarinTrainingCategory,
  texts: readonly string[],
): MandarinTrainingExercise[] {
  const seen = new Set<string>()

  return texts.map((text, index) => {
    const normalized = text.trim()
    const length = countVisibleChars(normalized)

    if (!normalized) {
      throw new Error(`[training corpus] ${category} contains an empty sentence`)
    }

    if (length < MIN_TEXT_LENGTH || length > MAX_TEXT_LENGTH) {
      throw new Error(
        `[training corpus] ${category} sentence length must be 6-16 chars: "${normalized}" (${length})`,
      )
    }

    if (seen.has(normalized)) {
      throw new Error(`[training corpus] ${category} contains duplicate sentence: "${normalized}"`)
    }
    seen.add(normalized)

    return {
      id: `${category}_curated_${String(index + 1).padStart(3, '0')}`,
      text: normalized,
      category,
    }
  })
}

